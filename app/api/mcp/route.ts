// app/api/mcp/route.ts
import { NextRequest, NextResponse } from 'next/server';

export async function GET() {
  return NextResponse.json({
    protocol: "MCP",
    version: "1.0.0",
    name: "Snake Rush Plum MCP Endpoint",
    status: "active",
    description: "Active MCP server for Snake Rush Plum Orchestrator Agent",
    capabilities: ["snake-rush-mechanics", "fast-paced-automation", "plum-collection"],
    timestamp: new Date().toISOString()
  });
}

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    return NextResponse.json({
      status: "success",
      message: "MCP command received",
      agent: "Snake Rush Plum Orchestrator",
      receivedAt: new Date().toISOString(),
      payload: body
    });
  } catch (error) {
    return NextResponse.json({ error: "Invalid MCP request" }, { status: 400 });
  }
}
